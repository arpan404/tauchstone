"""Repository protocol + Mock / Parquet implementations.

Mock mode serves contracts/fixtures/mock_world.json (generated by
services/api/scripts/make_mock_world.py). Real-data mode reads
$TS_DATA_DIR/processed via DuckDB per contracts/parquet/README.md.
"""

from __future__ import annotations

import json
import threading
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Protocol

from app.services.engine_adapter import Context, HiddenRow, Observation

REPO_ROOT = Path(__file__).resolve().parents[4]
MOCK_WORLD_PATH = REPO_ROOT / "contracts" / "fixtures" / "mock_world.json"
MOCK_PROVENANCE = {
    "dataset_accession": "MOCK",
    "processing_version": "mock-0.1",
    "git_commit": "mock",
    "timestamp": "2026-11-06T00:00:00Z",
}

COHORT_TISSUE = {
    "GSE132903": "middle temporal gyrus",
    "GSE173955": "hippocampus",
    "GSE53697": "unspecified",
}
COHORT_N = {  # (n_ad, n_control); see final report for the ordering assumption
    "GSE132903": (97, 98),
    "GSE53697": (9, 8),
    "GSE173955": (8, 10),
}
COHORT_METHOD = {"GSE132903": "limma", "GSE53697": "deseq2", "GSE173955": "limma-trend"}

SIGN_CHECK_EXPECTED = {
    "GFAP": "up",
    "CD44": "up",
    "SERPINA3": "up",
    "SST": "down",
    "VGF": "down",
    "NPTX2": "down",
    "BDNF": "down",
}


class NotFoundError(KeyError):
    pass


@dataclass
class ClaimInfo:
    text: str
    theta: float
    q: float = 0.7


@dataclass
class AttackWorld:
    candidate_id: str
    candidate_name: str
    hidden: list[HiddenRow] = field(default_factory=list)
    ranking: list[Observation] = field(default_factory=list)
    claim: ClaimInfo | None = None


class Repository(Protocol):
    def get_signature(self, cohort: str, variant: str) -> dict: ...
    def list_candidates(self, limit: int) -> dict: ...
    def get_evidence(self, candidate_id: str) -> dict: ...
    def get_attack_world(self, candidate_id: str) -> AttackWorld: ...
    def get_benchmark(self) -> dict: ...


def sign_check_for(genes: list[dict]) -> list[dict]:
    by_symbol = {g["symbol"]: g for g in genes}
    out = []
    for symbol, expected in SIGN_CHECK_EXPECTED.items():
        g = by_symbol.get(symbol)
        if g is None:
            continue
        stat = g["stat"]
        matches = (stat > 0) if expected == "up" else (stat < 0)
        out.append({"symbol": symbol, "expected": expected, "stat": stat, "matches": matches})
    return out


