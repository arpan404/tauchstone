def display_name(name: object) -> str:
    """Readable drug name: title-case plain names (RESVERATROL -> Resveratrol) but keep codes
    with digits as they are (LY-2886721, CPI-1189)."""
    s = str(name)
    return s if any(ch.isdigit() for ch in s) else s.title()

class NotFoundError(Exception):
    pass


@dataclass
class ClaimInfo:
    text: str
    theta: float
    q: float = 0.7


@dataclass
class AttackWorld:
    candidate_id: str
    candidate_name: str
    hidden: list[HiddenRow] = field(default_factory=list)
    ranking: list[Observation] = field(default_factory=list)
    claim: ClaimInfo | None = None
    engine_cfg: object = None  # real pipelines EngineConfig (parquet mode only)
    preregistered: bool = True  # False: hidden tests built on the fly (not preregistered)


class Repository(Protocol):
    def get_signature(self, cohort: str, variant: str) -> dict: ...
    def list_candidates(self, limit: int) -> dict: ...
    def get_evidence(self, candidate_id: str) -> dict: ...
    def get_attack_world(self, candidate_id: str) -> AttackWorld: ...
    def get_single_cell(self) -> dict: ...
    def get_benchmark(self) -> dict: ...
    def get_structure_path(self, pdb_id: str) -> Path: ...


def sign_check_for(genes: list[dict]) -> list[dict]:
    by_symbol = {g["symbol"]: g for g in genes}
    out = []
    for symbol, expected in SIGN_CHECK_EXPECTED.items():
        g = by_symbol.get(symbol)
        if g is None:
            continue
        stat = g["stat"]
        matches = (stat > 0) if expected == "up" else (stat < 0)
        out.append({"symbol": symbol, "expected": expected, "stat": stat, "matches": matches})
    return out


