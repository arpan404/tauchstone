class MockRepository:
    """Loads the generated mock world once (read-only cache, thread-safe)."""

    _lock = threading.Lock()
    _world: dict | None = None
    _path: Path | None = None

    def __init__(self, path: Path | None = None) -> None:
        self.path = path or MOCK_WORLD_PATH

    def _load(self) -> dict:
        with self._lock:
            if MockRepository._world is None or MockRepository._path != self.path:
                with open(self.path) as f:
                    MockRepository._world = json.load(f)
                MockRepository._path = self.path
            assert MockRepository._world is not None
            return MockRepository._world

    def get_signature(self, cohort: str, variant: str) -> dict:
        sigs = self._load()["signatures"]
        key = f"{cohort}__{variant}"
        if key not in sigs:
            raise NotFoundError(key)
        sig = dict(sigs[key])
        genes = sig["genes"]
        sig.setdefault("n_fdr05", sum(1 for g in genes if g["fdr"] < 0.05))
        sig.setdefault("sign_check", sign_check_for(genes))
        return sig

    def list_candidates(self, limit: int) -> dict:
        world = self._load()
        cands = world["candidates"][:limit]
        return {
            "signature": world.get("ranking_signature", "GSE132903__main"),
            "n_ranked": len(world["candidates"]),
            "permutation_control": world.get("permutation_control"),
            "candidates": cands,
            "provenance": world.get("provenance", MOCK_PROVENANCE),
        }

    def get_evidence(self, candidate_id: str) -> dict:
        ev = self._load()["evidence"]
        if candidate_id not in ev:
            raise NotFoundError(candidate_id)
        return ev[candidate_id]

    def get_attack_world(self, candidate_id: str) -> AttackWorld:
        world = self._load()
        if candidate_id not in world["truth"]:
            raise NotFoundError(candidate_id)
        hidden = [
            HiddenRow(
                context=Context(
                    context_id=r["context_id"],
                    type=r["context_type"],
                    label=r["label"],
                    tissue=r.get("tissue"),
                    region=r.get("region"),
                    platform=r.get("platform"),
                    cell_id=r.get("cell_id"),
                    pert_idose=r.get("pert_idose"),
                    pert_itime=r.get("pert_itime"),
                    cohort=r.get("cohort"),
                ),
                outcome=r["outcome"],
                value=r.get("value"),
                threshold=r.get("threshold"),
                rule=r.get("rule", ""),
                detail=r.get("detail", ""),
            )
            for r in world["truth"][candidate_id]
        ]
        ranking = [
            Observation(
                context=Context(
                    context_id=o["context_id"],
                    type="lincs_context",
                    label=o.get("label", o["context_id"]),
                    cell_id=o.get("cell_id"),
                    pert_idose=o.get("pert_idose"),
                    pert_itime=o.get("pert_itime"),
                ),
                survive=o["survive"],
                source="ranking",
            )
            for o in world["ranking_observations"].get(candidate_id, [])
        ]
        theta = world.get("permutation_control", {}).get("theta", -1.0)
        name = next(
            (c["name"] for c in world["candidates"] if c["id"] == candidate_id), candidate_id
        )
        return AttackWorld(
            candidate_id=candidate_id,
            candidate_name=name,
            hidden=hidden,
            ranking=ranking,
            claim=ClaimInfo(
                text=f"{name} reverses the AD signature in at least 70% of predefined validation contexts",
                theta=theta,
            ),
        )

    def get_single_cell(self) -> dict:
        return json.loads((REPO_ROOT / "contracts/fixtures/getSingleCellExploratory.json").read_text())

    def get_benchmark(self) -> dict:
        bench = self._load().get("benchmark")
